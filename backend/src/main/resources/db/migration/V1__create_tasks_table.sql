-- Estado do banco ao fim da Fase 3, quando o Flyway foi adotado.
-- Em produção esta migração NÃO roda: o banco já existia, então o Flyway só registra
-- a versão 1 como ponto de partida (spring.flyway.baseline-on-migrate=true).
-- Em bancos novos (testes com Testcontainers, máquina de outro dev) ela cria a tabela do zero.

CREATE TABLE tasks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              VARCHAR(255),
    description        VARCHAR(255),
    status             VARCHAR(255),
    priority           VARCHAR(255),
    category           VARCHAR(255),
    due_date           DATE,
    suggestion         VARCHAR(255),
    suggested_priority VARCHAR(20),
    suggested_category VARCHAR(20),
    subtasks           VARCHAR(2000),
    suggestion_source  VARCHAR(20),
    created_at         TIMESTAMP(6),
    updated_at         TIMESTAMP(6)
);
