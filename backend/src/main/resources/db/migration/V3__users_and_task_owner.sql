-- Contas de usuário: cada tarefa passa a ter um dono.

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Guardado sempre em minúsculas: "Ana" e "ana" são o mesmo usuário.
    username             VARCHAR(20)  NOT NULL UNIQUE,
    -- Hash BCrypt (60 caracteres). Nulo para visitantes, que não têm senha.
    password_hash        VARCHAR(100),
    guest                BOOLEAN      NOT NULL,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Última atividade: usada para apagar visitantes abandonados.
    last_seen_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Tokens emitidos ANTES deste instante são recusados (ex.: o token de visitante após virar conta).
    tokens_valid_after   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Orçamento diário de sugestões geradas pela IA.
    ai_suggestions_day   DATE,
    ai_suggestions_count INTEGER      NOT NULL DEFAULT 0
);

-- As tarefas que existiam até aqui não pertencem a ninguém (a lista era compartilhada por todos
-- os visitantes). Por decisão do dono do projeto, elas são descartadas em vez de "adotadas".
DELETE FROM tasks;

-- ON DELETE CASCADE: apagar um usuário (ex.: visitante inativo) apaga as tarefas dele junto.
ALTER TABLE tasks ADD COLUMN user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE;

-- Toda listagem filtra por dono; sem índice, cada uma leria a tabela inteira.
CREATE INDEX idx_tasks_user_id ON tasks (user_id);
